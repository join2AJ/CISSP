"""Build assets/js/grc-iso.js: the 93 ISO/IEC 27001:2022 Annex A controls with theme, description, new flag and 2013 equivalents.
Source: Claude-Skills-Governance-Risk-and-Compliance by Hemant Naik (MIT), iso27001 skill references.
Usage: python3 -I grc/build_iso.py <unzipped skills dir> <out.js>"""
import sys, re, json
src, out = sys.argv[1], sys.argv[2]
def rows(path):
    for ln in open(path, encoding="utf-8"):
        if ln.startswith("| A."):
            yield [c.strip() for c in ln.strip().strip("|").split("|")]
desc = {r[0]: r for r in rows(src + "/iso27001/iso27001/references/annex-a-2022.md")}
old = {r[0]: r[2] for r in rows(src + "/iso27001/iso27001/references/control-mapping.md") if len(r) >= 3 and re.match(r"A\.[5-8]\.\d+$", r[0])}
theme = {"5": "Organisational", "6": "People", "7": "Physical", "8": "Technological"}
data = []
for cid, r in desc.items():
    if not re.match(r"A\.[5-8]\.\d+$", cid): continue
    name = re.sub(r"\s*⭐\s*NEW", "", r[1]).strip()
    o = old.get(cid, "")
    data.append({"id": cid[2:], "name": name, "desc": r[2].replace("—", "-"), "theme": theme[cid[2]], "new": "NEW" in r[1] or "NEW" in o,
                 "old": "" if "NEW" in o else o})
assert len(data) == 93, len(data)
open(out, "w", encoding="utf-8").write("/* ISO/IEC 27001:2022 Annex A index (titles, short descriptions, 2013 equivalents). From Claude-Skills-Governance-Risk-and-Compliance\n   by Hemant Naik, MIT licence; see THIRD-PARTY-NOTICES.md. Generated by grc/build_iso.py. */\nwindow.ISO_2022 = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(data), "controls,", sum(d["new"] for d in data), "new")
